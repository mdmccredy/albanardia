#!/usr/bin/env python3
"""Albanardia stories: one database (stories/stories.json) for every website.

Builds stories/data.js, an "All stories" page for every site that doesn't have its own,
the master page at stories/ (every story from every site), and the news sections that
show the latest stories on each site. To add a story, append it to stories/stories.json
and run this script (it also re-runs the club and college generators).

Story fields: site, slug, date (YYYY-MM-DD), cat, title, dek, body [paragraphs], img, link
(link = the story's own page on a site with native articles), added ('original' or a date),
native (sbpl/sbps only: the article in that site's own format)."""
import ast, html, json, pathlib, re, subprocess
ROOT = pathlib.Path(__file__).resolve().parent.parent
E = html.escape
DB = json.loads((ROOT/'stories/stories.json').read_text())
ST = DB['stories']

def clubs():
    s = (ROOT/'tools/build_clubs.py').read_text(); i = s.index('C = ['); j = s.index('\n]\n', i)
    return ast.literal_eval(s[i+4:j+2])
def colleges():
    s = (ROOT/'tools/build_colleges.py').read_text(); i = s.index('S = ['); j = s.index('\n]\n', i)
    return eval(s[i+4:j+2])
def club_slug(c): return c[2].lower() if c[0] not in ('WYC-W', 'WYC-Wil') else ('waterloo-yc' if c[0] == 'WYC-W' else 'willamette-bc')

SITES = {
 'state': dict(name='Albanardia.gov', home='', stories='stories/', c1='#22498a', c2='#0f2340', group='State & city'),
 'gov': dict(name='City of Silverbrooks', home='gov/', stories='gov/stories/', c1='#0b2a5b', c2='#b5121b', group='State & city'),
 'times': dict(name='The Silverbrooks Times', home='media/times/', stories='media/times/stories/', c1='#1d1d1f', c2='#4a4a4f', group='News & media'),
 'uninews': dict(name='University News', home='media/university-news/', stories='media/university-news/stories/', c1='#b3122e', c2='#4a0814', group='News & media'),
 'sbpl': dict(name='Silverbrooks Public Library', home='sbpl/', stories='sbpl/#news', c1='#096d49', c2='#0f2882', group='Public services'),
 'sbps': dict(name='Silverbrooks Public Schools', home='sbps/', stories='sbps/#news', c1='#1a3363', c2='#890000', group='Public services'),
 'visit': dict(name='Visit Silverbrooks', home='visit/', stories='visit/stories/', c1='#0d2d4f', c2='#c4552f', group='Public services'),
 'larssen': dict(name='Larssen Sailing', home='larssensailing/', stories='larssensailing/#/news', c1='#0e2a66', c2='#c8102e', group='Business'),
}
for c in colleges():
    SITES['college:' + c['slug']] = dict(name=c['name'], home=f"colleges/{c['slug']}/", stories=f"colleges/{c['slug']}/stories/", c1=c['c1'], c2=c['c2'], group='Colleges')
for c in clubs():
    sl = club_slug(c); cd = c[2].lower(); page = (ROOT/f'{cd}/index.html')
    m = re.search(r'--c:(#[0-9a-fA-F]{3,6})', page.read_text()) if page.exists() else None
    SITES['club:' + sl] = dict(name=c[1], home=f'{cd}/', stories=f'{cd}/stories/', c1=m.group(1) if m else '#22498a', c2='#0f2340', group='Sailing clubs')
SITES['sbx'] = dict(name='SBX Airport', home='flysbx/', stories='flysbx/stories/', c1='#0b2545', c2='#ffc72c', group='Public services')
SITES['nesf'] = dict(name='Northeastern Sailing Foundation', home='nesf/', stories='nesf/stories/', c1='#0b4f6c', c2='#0a2233', group='Sailing clubs')
SITES['ayrc'] = dict(name='AYRC', home='nesf/ayrc/', stories='nesf/ayrc/stories/', c1='#c4552f', c2='#0a2233', group='Sailing clubs')
for s in ST: assert s['site'] in SITES, s['site']

# ---- data.js ----
pub = [{k: v for k, v in s.items() if k != 'native'} for s in ST]
(ROOT/'stories/data.js').write_text('/* generated by tools/build_stories.py from stories/stories.json */\nwindow.ALB_STORIES=' + json.dumps(dict(sites=SITES, stories=pub), ensure_ascii=False, separators=(',', ':')) + ';\n')

# ---- "All stories" pages ----
def page(key, path):
    depth = path.count('/') + 1; r = '../' * depth
    si = SITES.get(key, SITES['state'])
    name = 'Albanardia' if not key else si['name']
    out = ROOT/path/'index.html'; out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(f'''<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">
<title>All stories | {E(name)}</title><meta name="description" content="{'Every story from every Albanardia website.' if not key else 'Every story from ' + E(name) + '.'}">
<meta name="theme-color" content="{si['c1']}"><link rel="manifest" href="{r}manifest.json"><link rel="apple-touch-icon" href="{r}icons/icon-180.png"><link rel="icon" href="{r}icons/favicon.png">
<link rel="stylesheet" href="{r}app/stories.css"></head>
<body class="as-page"><div id="alb-stories" data-site="{key}"></div>
<script src="{r}stories/data.js"></script><script src="{r}app/stories.js" data-root="{r}"></script>
<!--app-shell--><script src="{r}app/app.js" data-home="float"></script><!--/app-shell-->
</body></html>
''')
page('', 'stories')
for k, v in SITES.items():
    if v['stories'].endswith('stories/') and k != 'state': page(k, v['stories'].rstrip('/'))

# ---- helpers for injecting into hand-built sites ----
def inject(path, pairs, head=True):
    p = ROOT/path; s = p.read_text(); depth = path.count('/'); r = '../' * depth
    s = re.sub(r'<!--alb-stories-->.*?<!--/alb-stories-->', '', s, flags=re.S)
    for anchor, html_, before in pairs:
        assert anchor in s, (path, anchor[:60])
        blk = f'<!--alb-stories-->{html_}<!--/alb-stories-->'
        s = s.replace(anchor, blk + anchor if before else anchor + blk, 1)
    if head:
        s = s.replace('</head>', f'<!--alb-stories--><link rel="stylesheet" href="{r}app/stories.css"><!--/alb-stories--></head>', 1)
        tail = f'<!--alb-stories--><script src="{r}stories/data.js"></script><script src="{r}app/stories.js" data-root="{r}"></script><!--/alb-stories-->'
        s = s.replace('</body>', tail + '</body>', 1)
    p.write_text(s)
def embed(key, title, n=3, style=''):
    return f'<section class="as-wrap" style="--as1:{SITES[key]["c1"]};{style}"><div data-alb-latest="{key}" data-n="{n}" data-title="{E(title)}"></div></section>'

# homepage (Albanardia.gov): state news, links to the master page
inject('index.html', [
 ('<a href="media/times/">The Times →</a></div>', '<a href="stories/" style="margin-right:14px">All stories →</a>', True),
 ('<a href="media/reels/">Reels</a>', '<a href="stories/">All stories</a>', True),
 ('<section class="blk" id="news">', '<section class="blk" style="padding-bottom:0"><div style="--as1:#22498a"><div data-alb-latest="state" data-n="3" data-title="State news"></div></div></section>', True)])

# City of Silverbrooks: native NEWS array from the database, cards open the story
gv = ROOT/'gov/index.html'; s = gv.read_text()
MON = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec']
G = sorted([x for x in ST if x['site'] == 'gov'], key=lambda x: x['date'], reverse=True)
arr = 'const NEWS=[' + ',\n'.join(json.dumps(['%s %d, %s' % (MON[int(x['date'][5:7]) - 1], int(x['date'][8:]), x['date'][:4]), x['title'], x['cat'], x['slug']], ensure_ascii=False) for x in G) + '];\n'
i = s.index('const NEWS='); j = s.index('const nc=', i); s = s[:i] + arr + s[j:]
s = re.sub(r'const nc=n=>`.*?`;', 'const nc=n=>`<a class="c" href="stories/#${n[3]}" style="display:block;color:inherit;text-decoration:none"><div class="d">Published ${n[0]} · ${n[2]}</div><h3 style="margin-top:4px">${n[1]}</h3></a>`;', s, count=1)
s = re.sub(r'<h2[^>]*>City news.*?</h2>', '<h2 style="display:flex;justify-content:space-between;align-items:baseline;gap:12px">City news <a href="stories/" style="font-size:15px;font-weight:700">All stories →</a></h2>', s, count=1)
s = re.sub(r'<h2>News</h2><div class="g news" id="allnews"></div>(<p>.*?</p>)?', '<h2>News</h2><div class="g news" id="allnews"></div><p><a href="stories/" style="font-weight:700">All stories, with full articles →</a></p>', s, count=1)
gv.write_text(s)

# Library and Schools: native article lists
for site in ('sbpl', 'sbps'):
    p = ROOT/f'{site}/index.html'; s = p.read_text()
    i = s.index('const DATA=') + 11; D, end = json.JSONDecoder().raw_decode(s, i)
    have = {a['slug'] for a in D['arts']}
    add = [x['native'] for x in sorted(ST, key=lambda x: x['date']) if x['site'] == site and x.get('native') and x['slug'] not in have]
    for a in add: D['arts'].insert(0, a)
    s = s[:i] + json.dumps(D, ensure_ascii=False) + s[end:]
    p.write_text(s)

# Larssen Sailing: native NEWS list (stories with a "native" entry in Larssen's format:
# [category, title, dek, image, slug, [paragraphs], [product names], "Month D, YYYY"])
p = ROOT/'larssensailing/index.html'; s = p.read_text()
m = re.search(r'const NEWS=(\[.*?\]);', s); N = json.loads(m.group(1)); have = {n[4] for n in N}
for x in sorted([x for x in ST if x['site'] == 'larssen' and x.get('native') and x['slug'] not in have], key=lambda x: x['date']):
    N.insert(0, x['native'])
s = s[:m.start(1)] + json.dumps(N, ensure_ascii=False) + s[m.end(1):]; p.write_text(s)

# The Times, University News, Visit Silverbrooks: latest stories boxes
inject('media/times/index.html', [('<section class="pg" id="front" aria-label="Section A, News">', embed('times', 'Latest from the Times', 3, 'display:block;max-width:1200px;margin:16px auto 6px;padding:0 16px'), True)])
inject('media/university-news/index.html', [('<section class="sec" aria-label="Campus briefs">', embed('uninews', 'Latest stories', 3, 'display:block;margin:10px 0 26px'), True)])
v = re.sub(r'<!--alb-stories-->.*?<!--/alb-stories-->', '', (ROOT/'visit/index.html').read_text(), flags=re.S)
k = v.index('<section class="pg" id="p-todo">'); k = v.rindex('</section>', 0, k)
inject('visit/index.html', [(v[k - 80:k], embed('visit', 'Latest from Visit Silverbrooks', 3, 'display:block;margin:28px 0 8px'), False)])

# ---- PUBLISH DATES: every story shows when it was published ----
MONL = ['January','February','March','April','May','June','July','August','September','October','November','December']
DAYN = ['Monday','Tuesday','Wednesday','Thursday','Friday','Saturday','Sunday']
import datetime as _dt
def pub_short(d): return '%s %d, %s' % (MON[int(d[5:7]) - 1], int(d[8:]), d[:4])
def pub_long(d): x = _dt.date.fromisoformat(d); return '%s, %s %d, %d' % (DAYN[x.weekday()], MONL[x.month - 1], x.day, x.year)
PUBTAG = re.compile(r'<!--alb-pub-->.*?<!--/alb-pub-->', re.S)
def pubmark(path, site, style):
    p = ROOT/path; s = PUBTAG.sub('', p.read_text())
    for x in ST:
        if x['site'] != site: continue
        t = html.escape(x['title'], quote=False)
        m = re.search(re.escape(t) + r'\s*</h[1-4]>', s)
        if m: s = s[:m.end()] + f'<!--alb-pub--><p class="alb-pub" style="{style}">Published {pub_long(x["date"])}<' + '/p><!--/alb-pub-->' + s[m.end():]
    p.write_text(s)
pubmark('media/times/index.html', 'times', 'font:600 11.5px/1.4 Inter,system-ui,sans-serif;letter-spacing:.6px;text-transform:uppercase;color:#6b6b70;margin:4px 0 8px')
pubmark('media/university-news/index.html', 'uninews', 'font:700 11.5px/1.4 system-ui,sans-serif;letter-spacing:.6px;text-transform:uppercase;color:#7a6b6b;margin:4px 0 8px')
# homepage top stories (they come from the Times and University News)
p = ROOT/'index.html'; s = PUBTAG.sub('', p.read_text())
for x in ST:
    if x['site'] not in ('times', 'uninews'): continue
    t = html.escape(x['title'], quote=False)
    for m in reversed(list(re.finditer(re.escape(t) + r'</h[34]>', s))):
        s = s[:m.end()] + f'<!--alb-pub--><span class="alb-pub" style="display:block;font-size:12.5px;color:var(--mut,#667);margin-top:3px">Published {pub_short(x["date"])}</span><!--/alb-pub-->' + s[m.end():]
p.write_text(s)
# Library and Schools: a published date on every article card and article page
for site in ('sbpl', 'sbps'):
    p = ROOT/f'{site}/index.html'; s = p.read_text()
    i = s.index('const DATA=') + 11; D, end = json.JSONDecoder().raw_decode(s, i)
    pubs = {x['slug']: x['date'] for x in ST if x['site'] == site}
    for a_ in D['arts']:
        if a_['slug'] in pubs: a_['pub'] = pub_short(pubs[a_['slug']])
    s = s[:i] + json.dumps(D, ensure_ascii=False) + s[end:]
    old = '<div class="d">${a.date} · ${a.kind}</div>'
    new = old + '${a.pub?`<div class="d" style="margin-top:2px;opacity:.8">Published ${a.pub}</div>`:\'\'}'
    if new not in s: s = s.replace(old, new)
    p.write_text(s)
# Larssen Sailing: every NEWS item carries its date, shown on the cards
p = ROOT/'larssensailing/index.html'; s = p.read_text()
m = re.search(r'const NEWS=(\[.*?\]);', s); N = json.loads(m.group(1))
dates = {x['slug']: x['date'] for x in ST if x['site'] == 'larssen'}
for n in N:
    while len(n) < 8: n.append([] if len(n) == 6 else '')
    if n[4] in dates: n[7] = '%s %d, %s' % (MONL[int(dates[n[4]][5:7]) - 1], int(dates[n[4]][8:]), dates[n[4]][:4])
s = s[:m.start(1)] + json.dumps(N, ensure_ascii=False) + s[m.end(1):]
s = s.replace("${n[0]} · ${n[7]||'November 2026'}", "${n[0]} · Published ${n[7]||'November 2026'}")
s = s.replace('<small>${n[0]}</small><h3>${n[1]}</h3>', '<small>${n[0]}${n[7]?\' · Published \'+n[7]:\'\'}</small><h3>${n[1]}</h3>')
p.write_text(s)

# clubs and colleges: generators render the news sections from the database
subprocess.run(['python3', str(ROOT/'tools/build_clubs.py')], check=True, stdout=subprocess.DEVNULL)
subprocess.run(['python3', str(ROOT/'tools/build_colleges.py')], check=True, stdout=subprocess.DEVNULL)
subprocess.run(['python3', str(ROOT/'tools/build_port.py')], check=True, stdout=subprocess.DEVNULL)
subprocess.run(['python3', str(ROOT/'tools/build_sbx.py')], check=True, stdout=subprocess.DEVNULL)
subprocess.run(['python3', str(ROOT/'tools/build_nesf.py')], check=True, stdout=subprocess.DEVNULL)
